function getLang() {
  var saved = null;
  try { saved = localStorage.getItem('shlep_lang'); } catch (e) {}
  if (saved && window.SHLEP_T[saved]) return saved;
  var nav = (navigator.language || 'de').slice(0, 2).toLowerCase();
  return window.SHLEP_T[nav] ? nav : 'de';
}

function applyLang(lang) {
  var dict = window.SHLEP_T[lang] || window.SHLEP_T.de;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var k = el.getAttribute('data-i18n');
    if (dict[k] != null) el.textContent = dict[k];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    var k = el.getAttribute('data-i18n-ph');
    if (dict[k] != null) el.setAttribute('placeholder', dict[k]);
  });
  document.querySelectorAll('#langsw button').forEach(function (b) {
    b.classList.toggle('on', b.getAttribute('data-lang') === lang);
  });
  try { localStorage.setItem('shlep_lang', lang); } catch (e) {}
  if (typeof onLangApplied === 'function') onLangApplied(lang);
}

document.addEventListener('click', function (e) {
  var b = e.target.closest && e.target.closest('#langsw button');
  if (b) applyLang(b.getAttribute('data-lang'));
});
